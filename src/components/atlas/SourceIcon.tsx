type Props = {
  source: string | null | undefined;
  url?: string | null;
  className?: string;
};

/** Small brand mark for a track's source, linking out to the track when a URL exists. */
export function SourceIcon({ source, url, className }: Props) {
  const label = sourceLabel(source) ?? "Source";
  const path = source ? PATHS[source] : undefined;

  const glyph = path ? (
    <svg
      viewBox="0 0 24 24"
      fill="currentColor"
      aria-hidden="true"
      className={className ?? "h-4 w-4"}
    >
      <path d={path} />
    </svg>
  ) : source === "discogs" ? (
    <Disc3 aria-hidden="true" className={className ?? "h-4 w-4"} />
  ) : url ? (
    <ExternalLink aria-hidden="true" className={className ?? "h-4 w-4"} />
  ) : null;

  if (!glyph) return null;

  if (!url) {
    return (
      <span className="inline-flex text-muted-foreground" title={label}>
        {glyph}
        <span className="sr-only">{label}</span>
      </span>
    );
  }

  return (
    <a
      href={url}
      target="_blank"
      rel="noreferrer"
      title={`Open on ${label}`}
      className="inline-flex text-muted-foreground transition-colors hover:text-primary"
    >
      {glyph}
      <span className="sr-only">Open on {label}</span>
    </a>
  );
}
